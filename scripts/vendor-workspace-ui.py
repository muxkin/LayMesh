#!/usr/bin/env python3
"""Rebuild offline workspace UI adapters from pinned, checked upstream files. No npm."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def build():
 root=ROOT/'vendor/workspace-ui';meta=json.loads((root/'manifest.json').read_text());parts=['// Generated by scripts/vendor-workspace-ui.py; private UMD module scopes.']
 for package,info in meta.items():
  for name,digest in info['files'].items():assert hashlib.sha256((root/name).read_bytes()).hexdigest()==digest,name
 def read(name):return (root/name).read_text()
 parts+=['const jQuery=(()=>{const module={exports:{}};const exports=module.exports;\n'+read('jquery/jquery.min.js')+'\nreturn module.exports;})();']
 for name in ['jquery-contextmenu/jquery.ui.position.min.js','jquery-contextmenu/jquery.contextMenu.min.js']:
  parts+=['(()=>{const module={exports:{}};const exports=module.exports;const require=()=>jQuery;\n'+read(name)+'\n})();']
 parts+=['export default jQuery;']
 dest=ROOT/'site/vendor/workspace-ui';dest.mkdir(exist_ok=True);(dest/'index.js').write_text('\n'.join(parts));(dest/'LICENSE').write_text(read('jquery/LICENSE.txt')+'\n'+read('jquery-contextmenu/LICENSE'))
 css=read('jquery-contextmenu/jquery.contextMenu.min.css');css=re.sub(r'@font-face\s*\{[^}]*\}','',css);css=re.sub(r'url\([^)]*\)','none',css)
 (ROOT/'site/live/workspace-ui.css').write_text(css)
 tree=ROOT/'vendor/headless-tree';info=json.loads((tree/'manifest.json').read_text())
 for name,digest in info['files'].items():assert hashlib.sha256((tree/name).read_bytes()).hexdigest()==digest,name
 target=ROOT/'site/vendor/@headless-tree/core';target.mkdir(parents=True,exist_ok=True);(target/'index.js').write_bytes((tree/'dist/index.mjs').read_bytes());(target/'LICENSE').write_bytes((tree/'LICENSE').read_bytes())
 manifest=ROOT/'site/vendor/manifest.json';m=json.loads(manifest.read_text())
 for name,version in [('workspace-ui','contextmenu-2.10.2_jquery-3.7.1'),('@headless-tree/core',info['version'])]:
  m[name]={'version':version,'entry':name+'/index.js','sha256':hashlib.sha256((ROOT/'site/vendor'/name/'index.js').read_bytes()).hexdigest(),'license':name+'/LICENSE'}
 manifest.write_text(json.dumps(m,indent=2)+'\n')
if __name__=='__main__':build()
