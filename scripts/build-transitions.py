#!/usr/bin/env python3
"""Pin upstream GL Transitions and generate offline CSS, metadata and SkSL modules.

Run --download only to acquire the pinned package. Normal builds are offline.
"""
import argparse
import hashlib
import io
import json
import re
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.74.0"
TARBALL_SHA256 = "da755f31aa8fff8b3aec5973cb69ce3675b02db54ab6f511b718f8e73a7a08b2"
COMMIT = "e5056320c2b899c10e67076123a9f3d23e159094"
VENDOR = ROOT / "vendor/gl-transitions"
SOURCE = f"https://registry.npmjs.org/gl-transitions/-/gl-transitions-{VERSION}.tgz"


def write(path, content):
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main(download=False):
    if download:
        data = urllib.request.urlopen(SOURCE).read()
        assert hashlib.sha256(data).hexdigest() == TARBALL_SHA256, "Pinned package checksum mismatch"
        VENDOR.mkdir(parents=True, exist_ok=True)
        records = {}
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
            for member in archive:
                name = member.name.removeprefix("package/")
                if not member.isfile() or not (name in ["LICENSE", "gl-transitions.json"] or name.startswith(("sksl/", "transitions/"))):
                    continue
                if ".." in Path(name).parts or Path(name).is_absolute():
                    raise ValueError(name)
                content = archive.extractfile(member).read()
                dest = VENDOR / name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(content)
                records[name] = hashlib.sha256(content).hexdigest()
        converter = f"https://raw.githubusercontent.com/gl-transitions/gl-transitions/{COMMIT}/scripts/targets/"
        for name in ["build-sksl.mjs", "sksl.mjs"]:
            content = urllib.request.urlopen(converter + name).read()
            dest = VENDOR / "tools" / name
            dest.parent.mkdir(exist_ok=True)
            dest.write_bytes(content)
            records["tools/" + name] = hashlib.sha256(content).hexdigest()
        (VENDOR / "manifest.json").write_text(json.dumps({"version": VERSION, "source": SOURCE, "commit": COMMIT, "converter_source": converter, "tarball_sha256": hashlib.sha256(data).hexdigest(), "files": records}, indent=2) + "\n")
    manifest = json.loads((VENDOR / "manifest.json").read_text())
    for name, digest in manifest["files"].items():
        assert hashlib.sha256((VENDOR / name).read_bytes()).hexdigest() == digest, name
    catalog = json.loads((VENDOR / "gl-transitions.json").read_text())
    metadata, runtime = [], {}
    css = [f"/* GL Transitions {VERSION}; generated by scripts/build-transitions.py. */"]
    kebab = lambda s: re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", s).replace("_", "-").lower()
    for item in catalog:
        entry = {k: item[k] for k in ["name", "author", "license", "paramsTypes", "defaultParams", "params", "textures", "description", "tags"] if k in item}
        entry["cssParams"] = {kebab(k): k for k in item["paramsTypes"]}
        entry["cssTextures"] = {kebab(k): k for k in item.get("textures", [])}
        metadata.append(entry)
        runtime[item["name"]] = {**entry, "sksl": (VENDOR / "sksl" / (item["name"] + ".sksl")).read_text()}
        css.append(f'.gl-transition-{item["name"]} {{ -laymesh-transition: {item["name"]}; }}')
    assets = ROOT / "crates/laymesh-core/assets"
    write(assets / "transitions.json", json.dumps(metadata, ensure_ascii=False, indent=2) + "\n")
    css_path = assets / "styles/gl-transitions.css"
    write(css_path, "\n".join(css) + "\n")
    style_manifest = assets / "styles/manifest.json"
    styles = [v for v in json.loads(style_manifest.read_text()) if v["name"] != "gl-transitions"]
    styles.append({"name": "gl-transitions", "version": VERSION, "source": SOURCE, "sha256": hashlib.sha256(css_path.read_bytes()).hexdigest(), "license": "MIT, BSD-2-Clause, BSD-3-Clause", "license_source": "https://github.com/gl-transitions/gl-transitions/blob/master/LICENSE"})
    write(style_manifest, json.dumps(styles, indent=2) + "\n")
    write(ROOT / "site/live/presentation-transitions-data.mjs", "// Generated by scripts/build-transitions.py; upstream sources and licenses in vendor/gl-transitions.\nexport const transitions = " + json.dumps(runtime, ensure_ascii=False, separators=(",", ":")) + ";\n")
    notices = ["GL Transitions " + VERSION, (VENDOR / "LICENSE").read_text()]
    for item in catalog:
        notices.append(f"\n{item['name']} — {item['author']} — {item['license']}")
        # Preserve source comments, including copyright/license notices after
        # uniform declarations (StereoViewer) and notices using line comments.
        notices.append("\n".join(re.findall(r"//[^\n]*|/\*[\s\S]*?\*/", item["glsl"])))
    write(ROOT / "release/licenses/GL-Transitions.txt", "\n".join(notices) + "\n")
    write(assets / "styles/gl-transitions.LICENSE", "\n".join(notices) + "\n")
    table = ["| Effect / preset suffix | CSS parameter defaults | Extra texture | License |", "| --- | --- | --- | --- |"]
    for entry in metadata:
        params = "; ".join(f"`{k}`: `{json.dumps(entry['defaultParams'][v], separators=(',', ':'))}`" for k, v in entry["cssParams"].items()) or "—"
        table.append(f"| `{entry['name']}` | {params} | {', '.join(entry['cssTextures']) or '—'} | {entry['license']} |")
    for lang in ["zh-CN", "en"]:
        doc = ROOT / f"docs/topics/page-transitions.{lang}.md"
        if doc.exists():
            write(doc, doc.read_text().split("<!-- generated-catalog -->")[0] + "<!-- generated-catalog -->\n\n" + "\n".join(table) + "\n")
    print(f"Generated {len(catalog)} offline transitions ({VERSION})")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true")
    main(parser.parse_args().download)
