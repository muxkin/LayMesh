def ftcs(n,r=.4,stop=.05):
 h=1/n;steps=math.ceil(stop/(r*h*h));dt=stop/steps;r=dt/h**2;u=[math.sin(math.pi*i*h) for i in range(n+1)]
 for _ in range(steps):u=[0]+[u[i]+r*(u[i-1]-2*u[i]+u[i+1]) for i in range(1,n)]+[0]
 error=math.sqrt(sum((u[i]-exact(i*h,stop))**2 for i in range(n+1))/n)
 return {'n':n,'h':h,'dt':dt,'r':r,'steps':steps,'error':error,'values':u}
